import AppKit
import CryptoKit
import ImageIO

/// Clipboard history owns its image copies independently of the clothesline.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static var ownChangeCount = -1
    @Published private(set) var items: [HistoryClip] = []
    @Published private(set) var textLimit: Int
    @Published private(set) var imageLimit: Int
    @Published private(set) var deleted: HistoryClip?
    @Published var status: String?
    private var book: HistoryBook
    private let root: URL
    private let defaults: UserDefaults
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var undoGeneration = 0
    private var unreadableHistory = false
    private var knownImageFiles: Set<String> = []

    private static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL, .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType")
    ]
    private var file: URL { root.appendingPathComponent("clipboard-history.json") }
    private var images: URL { root.appendingPathComponent("ClipboardImages", isDirectory: true) }

    init(root: URL = AppFiles.root, defaults: UserDefaults = .standard) {
        self.root = root
        self.defaults = defaults
        let text = defaults.object(forKey: "historyTextLimit") as? Int ?? 1000
        let image = defaults.object(forKey: "historyImageLimit") as? Int ?? 100
        let file = root.appendingPathComponent("clipboard-history.json")
        let legacy = root.appendingPathComponent("text-clips.json")
        let source = FileManager.default.fileExists(atPath: file.path) ? file : legacy
        let loaded = (try? Data(contentsOf: source)).flatMap { try? JSONDecoder().decode([HistoryClip].self, from: $0) } ?? []
        book = HistoryBook(items: loaded, textLimit: text, imageLimit: image)
        textLimit = book.textLimit
        imageLimit = book.imageLimit
        items = book.items
        knownImageFiles = Set(loaded.compactMap(\.imageFilename))
        if FileManager.default.fileExists(atPath: file.path),
           let data = try? Data(contentsOf: file),
           (try? JSONDecoder().decode([HistoryClip].self, from: data)) == nil {
            unreadableHistory = true
            status = L("Could not save clipboard history")
        }
        // The old text file stays untouched. Migration is committed on the next successful save.
    }

    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func matches(_ query: String) -> [HistoryClip] { book.matches(query) }

    func setLimits(text: Int? = nil, images: Int? = nil) {
        book.setLimits(text: text ?? textLimit, images: images ?? imageLimit)
        textLimit = book.textLimit
        imageLimit = book.imageLimit
        defaults.set(textLimit, forKey: "historyTextLimit")
        defaults.set(imageLimit, forKey: "historyImageLimit")
        publishAndSave()
    }

    func touch(_ id: UUID) {
        guard let clip = book.items.first(where: { $0.id == id }), clip.isImage else { return }
        book.touch(id)
        // LRU changes must survive a restart, but do not reorder the displayed copies.
        publishAndSave()
    }

    func remove(id: UUID) {
        undoGeneration += 1
        deleted = book.remove(id)
        publishAndSave()
        let generation = undoGeneration
        DispatchQueue.main.asyncAfter(deadline: .now() + 5) { [weak self] in
            guard let self, self.undoGeneration == generation else { return }
            self.deleted = nil
            self.publishAndSave()
        }
    }

    func undoDelete() -> UUID? {
        guard let clip = deleted else { return nil }
        undoGeneration += 1
        deleted = nil
        let restored = book.restore(clip)
        publishAndSave()
        return restored
    }

    func imageURL(for clip: HistoryClip) -> URL? {
        guard let name = clip.imageFilename, name == (name as NSString).lastPathComponent,
              name.hasSuffix(".png") else { return nil }
        return images.appendingPathComponent(name)
    }

    @discardableResult
    func copyToPasteboard(_ clip: HistoryClip) -> Bool {
        let pb = NSPasteboard.general
        if clip.isImage {
            guard let url = imageURL(for: clip), let data = try? Data(contentsOf: url),
                  NSImage(data: data) != nil else {
                status = L("This image cannot be read")
                return false
            }
            pb.clearContents()
            guard pb.setData(data, forType: .png) else { return false }
            book.touch(clip.id)
        } else {
            pb.clearContents()
            guard pb.setString(clip.text, forType: .string) else { return false }
        }
        lastCount = pb.changeCount
        Self.ownChangeCount = pb.changeCount
        publishAndSave()
        return true
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard count != Self.ownChangeCount,
              let entries = pb.pasteboardItems, !entries.isEmpty,
              entries.allSatisfy({ Self.skipTypes.isDisjoint(with: $0.types) }) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        if let text = pb.string(forType: .string) {
            if book.rememberText(text, source: source) != nil { publishAndSave() }
            return
        }
        guard let type = pb.availableType(from: [.png, .tiff]),
              let data = pb.data(forType: type), pb.changeCount == count else { return }
        guard data.count <= 64 * 1024 * 1024 else { status = L("Image exceeds the 64 MB limit"); return }
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let decoded = Self.decodeImage(data)
            DispatchQueue.main.async {
                guard let self, NSPasteboard.general.changeCount == count else { return }
                guard let decoded else { self.status = L("This image cannot be read"); return }
                self.rememberImage(decoded.png, width: decoded.width, height: decoded.height, source: source)
            }
        }
    }

    nonisolated static func decodeImage(_ data: Data) -> (png: Data, width: Int, height: Int)? {
        guard data.count <= 64 * 1024 * 1024,
              let src = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int,
              let height = props[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= 80_000_000 / height,
              let image = CGImageSourceCreateImageAtIndex(src, 0, nil) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        guard CGImageDestinationFinalize(dest), out.length <= 64 * 1024 * 1024 else { return nil }
        return (out as Data, width, height)
    }

    func rememberImage(_ png: Data, width: Int, height: Int, source: String?) {
        let key = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        let name = key + ".png"
        do {
            let fm = FileManager.default
            try fm.createDirectory(at: images, withIntermediateDirectories: true,
                                   attributes: [.posixPermissions: 0o700])
            let url = images.appendingPathComponent(name)
            if !fm.fileExists(atPath: url.path) {
                try png.write(to: url, options: .atomic)
                try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            }
            _ = book.rememberImage(key: key, filename: name, width: width, height: height,
                                   bytes: png.count, source: source)
            publishAndSave()
        } catch { status = L("Could not save clipboard history") }
    }

    private func publishAndSave() {
        items = book.items
        do {
            let fm = FileManager.default
            try fm.createDirectory(at: root, withIntermediateDirectories: true)
            if unreadableHistory {
                try fm.copyItem(at: file, to: root.appendingPathComponent("clipboard-history-" + UUID().uuidString + ".backup.json"))
                unreadableHistory = false
            }
            try JSONEncoder().encode(book.items).write(to: file, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            // Clean only owned images, and only after the metadata was safely committed.
            var keep = Set(book.items.compactMap(\.imageFilename))
            if let name = deleted?.imageFilename { keep.insert(name) }
            for name in knownImageFiles.subtracting(keep)
                where name == (name as NSString).lastPathComponent && name.hasSuffix(".png") {
                try? fm.removeItem(at: images.appendingPathComponent(name))
            }
            knownImageFiles = keep
        } catch { status = L("Could not save clipboard history") }
    }
}
