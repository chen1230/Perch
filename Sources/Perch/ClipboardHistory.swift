import AppKit

/// One piece of copied text. Screenshots are not stored here; they hang on the line.
struct TextClip: Identifiable, Codable, Equatable {
    var id: UUID
    var text: String
    var date: Date
}

/// Text copied to the clipboard, newest first. Images are left to the line.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [TextClip] = []

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private let limit = 100
    private let maxCharacters = 50_000

    private static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .fileURL,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private static var file: URL {
        return AppFiles.textClips
    }

    private init() {
        items = Self.load()
    }

    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func matches(_ query: String) -> [TextClip] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        guard !words.isEmpty else { return items }
        return items.filter { clip in
            words.allSatisfy { clip.text.localizedStandardContains($0) }
        }
    }

    /// Drops one saved string. The system clipboard is left as it is.
    func remove(id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items.remove(at: index)
        Self.save(items)
    }

    /// Puts the text on the clipboard. The watcher will see it and keep it at the top.
    func copyToPasteboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastCount = pb.changeCount
        remember(text)
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.skipTypes.isDisjoint(with: $0.types) }),
              let text = pb.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        remember(String(text.prefix(maxCharacters)))
    }

    private func remember(_ text: String) {
        if let index = items.firstIndex(where: { $0.text == text }) {
            var clip = items.remove(at: index)
            clip.date = Date()
            items.insert(clip, at: 0)
        } else {
            items.insert(TextClip(id: UUID(), text: text, date: Date()), at: 0)
            if items.count > limit { items.removeLast(items.count - limit) }
        }
        Self.save(items)
    }

    private static func load() -> [TextClip] {
        guard let data = try? Data(contentsOf: file),
              let clips = try? JSONDecoder().decode([TextClip].self, from: data) else { return [] }
        return clips
    }

    private static func save(_ items: [TextClip]) {
        let url = file
        let fm = FileManager.default
        do {
            try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            let data = try JSONEncoder().encode(items)
            try data.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        } catch {
            log.error("Could not save copied text: \(error.localizedDescription, privacy: .public)")
        }
    }
}

